def build_generated_ops(
    module_name: str, ops_config: dict[str, Any], operations: dict[str, Operation]
) -> list[GeneratedOp]:
    class_prefix = _pascal(module_name)
    generated = []
    for operation_id, cfg in ops_config.items():
        if operation_id not in operations:
            raise KeyError(
                f"resource-map.json module {module_name!r} references "
                f"operationId {operation_id!r}, which doesn't exist in "
                f"{SPEC_PATH}. Was the spec regenerated since the map was "
                f"written?"
            )
        op = operations[operation_id]
        method_name = cfg.get("method") or default_method_name(op.method, op.path)
        if keyword.iskeyword(method_name) or keyword.issoftkeyword(method_name):
            # e.g. POST /database/import defaulting to "import" — a
            # reserved word can't be a method name at all (SyntaxError),
            # not just an awkward one like the builtins.list collision.
            raise ValueError(
                f"{operation_id}: method name {method_name!r} is a Python "
                f'keyword. Add an explicit "method" override for this op '
                f"in resource-map.json's {module_name!r} module."
            )
        generated.append(GeneratedOp(op, method_name, class_prefix, module_name))
    return generated


def write_models_module(
    module_name: str, generated_ops: list[GeneratedOp], spec_version: str
) -> None:
    raw_classes = [g.emit_model_class() for g in generated_ops]
    classes = [c for c in raw_classes if c is not None]
    path = SRC / "models" / f"{module_name}.py"
    body = [
        GENERATED_HEADER.format(spec_version=spec_version),
        f'"""Response models for termix_sdk.resources.{module_name}."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Literal  # noqa: F401, UP035",
        "",
        "from .._object import TermixObject",
        "",
        "",
    ]
    body.append(
        "\n\n\n".join(classes)
        if classes
        else "# No dedicated response models for this pilot module.\n"
    )
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def write_types_module(
    module_name: str, generated_ops: list[GeneratedOp], spec_version: str
) -> None:
    raw_typeddicts = [g.emit_params_typeddict() for g in generated_ops]
    typeddicts = [t for t in raw_typeddicts if t is not None]
    path = SRC / "types" / f"{module_name}.py"
    body = [
        GENERATED_HEADER.format(spec_version=spec_version),
        f'"""Request param TypedDicts for termix_sdk.resources.{module_name}."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Literal  # noqa: F401, UP035",
        "",
        "from typing_extensions import TypedDict",
        "",
        "",
    ]
    body.append(
        "\n\n\n".join(typeddicts) if typeddicts else "# No operations in this module take params.\n"
    )
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def write_resources_module(
    module_name: str, generated_ops: list[GeneratedOp], service_default: str, spec_version: str
) -> None:
    class_prefix = _pascal(module_name)
    plain_model_names = {
        g._model_name_for(g.op.response_schema) for g in generated_ops if g.op.response_schema
    }
    plain_model_names_str: set[str] = {n for n in plain_model_names if n is not None}
    array_item_model_names = {
        f"{class_prefix}{_pascal(g.method_name)}Item"
        for g in generated_ops
        if g.op.response_schema
        and g.op.response_schema.get("type") == "array"
        and (g.op.response_schema.get("items") or {}).get("properties")
    }
    model_names = sorted(plain_model_names_str | array_item_model_names)
    param_names = sorted({g.params_class_name for g in generated_ops if g.has_params()})

    lines = [
        GENERATED_HEADER.format(spec_version=spec_version),
        f'"""{class_prefix}: generated resource module."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Literal  # noqa: F401, UP035",
        "",
        "from typing_extensions import Unpack",
        "",
        "from .._object import TermixObject",
        "from .._request_options import RequestOptions",
        "from .._service import AsyncTermixService, TermixService",
    ]
    if model_names:
        lines.append(f"from ..models.{module_name} import {', '.join(model_names)}")
    if param_names:
        lines.append(f"from ..types.{module_name} import {', '.join(param_names)}")
    lines += ["", ""]

    lines.append(f"class {class_prefix}Service(TermixService):")
    lines.append(f'    service = "{service_default}"')
    lines.append("")
    for g in generated_ops:
        lines.append(g.emit_method(is_async=False))
    lines.append("")

    lines.append(f"class Async{class_prefix}Service(AsyncTermixService):")
    lines.append(f'    service = "{service_default}"')
    lines.append("")
    for g in generated_ops:
        lines.append(g.emit_method(is_async=True))
    lines.append("")

    path = SRC / "resources" / f"{module_name}.py"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


CONTRACT_TESTS_ROOT = REPO_ROOT / "tests" / "contract"


def write_contract_test_module(module_name: str, generated_ops: list[GeneratedOp]) -> None:
    """tests/contract/test_<module>.py: docs/sdk-plan.md's testing-decision
    note. One test per generated op (sync) plus one more (async), using
    synthetic data — verifies the SDK's request/response handling against
    what the spec documents, not against a live Termix instance.
    """
    lines = [
        '"""Generated by tools/sdk-gen/generate.py. Do not edit by hand —',
        f' see docs/sdk-plan.md phases F3/F4. Covers termix_sdk.resources.{module_name}."""',
        "",
        "from __future__ import annotations",
        "",
        # Some real Termix response strings (e.g. encryption's warning
        # messages) or long paths (e.g. webauthn's credential routes) push
        # a generated line past 100 columns on their own. Nothing here is
        # meant to be read line-by-line by a human, so line length isn't
        # enforced for these files rather than truncating real API data
        # or the descriptive docstring to fit.
        "# ruff: noqa: E501",
        "",
        "import pytest",
        "",
        "",
    ]
    for g in generated_ops:
        lines.append(g.emit_contract_test(is_async=False))
    for g in generated_ops:
        lines.append(g.emit_contract_test(is_async=True))

    path = CONTRACT_TESTS_ROOT / f"test_{module_name}.py"
    path.write_text("\n".join(lines), encoding="utf-8")


REGION_RE_TEMPLATE = r"( *# --- {label} start ---\n).*?(\n *# --- {label} end ---)"


def rewrite_region(file_path: Path, label: str, new_body: str) -> None:
    text = file_path.read_text(encoding="utf-8")
    pattern = re.compile(REGION_RE_TEMPLATE.format(label=re.escape(label)), re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"{file_path}: marker region {label!r} not found")
    replacement = r"\1" + new_body + r"\2"
    text = pattern.sub(replacement, text, count=1)
    file_path.write_text(text, encoding="utf-8")


def wire_client(module_names: list[str]) -> None:
    # Sorted alphabetically so the generated block is already in the order
    # ruff's isort (I001) wants — otherwise `ruff check` on _client.py
    # flags it, and `--fix` would rewrite across the marker comments in a
    # way rewrite_region() can't safely re-target on the next run.
    sorted_names = sorted(module_names)

    for client_file, service_prefix in (
        (SRC / "_client.py", ""),
        (SRC / "_async_client.py", "Async"),
    ):
        import_lines = "\n".join(f"from .resources import {m} as _{m}" for m in sorted_names)
        rewrite_region(client_file, "generated resource imports", "\n" + import_lines + "\n")

        class_prefix_map = {m: _pascal(m) for m in sorted_names}
        attr_lines = "\n".join(
            f"        self.{m} = _{m}.{service_prefix}{class_prefix_map[m]}Service(self._requestor)"
            for m in sorted_names
        )
        rewrite_region(client_file, "generated resource attributes", "\n" + attr_lines + "\n")


def main() -> None:
    spec = load_spec()
    spec_version = spec.get("x-termix-source", {}).get("tag", "unknown")
    operations = index_operations(spec)
    resource_map = json.loads(MAP_PATH.read_text(encoding="utf-8"))

    module_names = list(resource_map["modules"])
    for module_name, module_cfg in resource_map["modules"].items():
        generated_ops = build_generated_ops(module_name, module_cfg["ops"], operations)
        service_default = generated_ops[0].op.service if generated_ops else "database"
        write_models_module(module_name, generated_ops, spec_version)
        write_types_module(module_name, generated_ops, spec_version)
        write_resources_module(module_name, generated_ops, service_default, spec_version)
        write_contract_test_module(module_name, generated_ops)
        print(f"generated {module_name}: {len(generated_ops)} operations")

    wire_client(module_names)
    print("wired client attributes:", ", ".join(module_names))

    format_generated_files(module_names)


def format_generated_files(module_names: list[str]) -> None:
    """The generator emits correct but unwrapped source (long signatures,
    long import lines) — `ruff format`/`ruff check --fix` normalize it to
    the project's own style rather than teaching generate.py to wrap lines
    itself. Run `python tools/sdk-gen/generate.py` from an environment
    that has the project's `dev` extra installed; this is a no-op (with a
    printed warning) if ruff isn't importable, so a bare install of the
    package alone doesn't fail here.
    """
    import shutil
    import subprocess

    ruff = shutil.which("ruff")
    if ruff is None:
        print(
            "note: `ruff` not found on PATH — generated files were written "
            "unformatted. Install the `dev` extra and re-run, or run "
            "`ruff format`/`ruff check --fix` yourself.",
            file=sys.stderr,
        )
        return

    targets = [
        str(SRC / kind / f"{m}.py")
        for kind in ("resources", "models", "types")
        for m in module_names
    ] + [str(CONTRACT_TESTS_ROOT / f"test_{m}.py") for m in module_names]
    subprocess.run([ruff, "format", *targets], check=True)
    subprocess.run([ruff, "check", "--fix", *targets], check=True)


if __name__ == "__main__":
    main()
