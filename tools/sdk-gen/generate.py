# JSON Schema -> Python type
# --------------------------------------------------------------------------


def schema_to_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "Any"
    if schema.get("x-confidence") == "unknown":
        return "Any"
    if "oneOf" in schema:
        return " | ".join(schema_to_type(v) for v in schema["oneOf"])
    if "anyOf" in schema:
        return " | ".join(schema_to_type(v) for v in schema["anyOf"])
    if "const" in schema:
        return f"Literal[{schema['const']!r}]"
    if "enum" in schema:
        return " | ".join(f"Literal[{v!r}]" for v in schema["enum"])

    t = schema.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        base = schema_to_type({**schema, "type": non_null[0]}) if len(non_null) == 1 else "Any"
        return f"{base} | None" if "null" in t else base

    if t == "object":
        return "Dict[str, Any]"
    if t == "array":
        return f"List[{schema_to_type(schema.get('items'))}]"
    if t == "string":
        return "str"
    if t in ("integer",):
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    return "Any"


def schema_allows_null(schema: dict[str, Any] | None) -> bool:
    """True when `schema` can legitimately produce a JSON `null` (and so
    `construct_from` will legitimately return `None`) — a plain `type:
    "null"` variant, a `type` list containing `"null"`, or any `oneOf`/
    `anyOf` branch that does. `GET /network-topology`'s `oneOf: [{unknown},
    {type: "null"}]` is the concrete case this was written for: without
    it, the generated return type promised `TermixObject` unconditionally
    even though `None` is a real, spec-documented outcome.
    """
    if not schema:
        return False
    t = schema.get("type")
    if t == "null" or (isinstance(t, list) and "null" in t):
        return True
    for key in ("oneOf", "anyOf"):
        if any(schema_allows_null(v) for v in schema.get(key, [])):
            return True
    return False


def resolve_array_items(schema: dict[str, Any] | None) -> dict[str, Any] | None:
    """If `schema` describes a JSON array — directly, or as a `oneOf`/
    `anyOf` where *every* variant is an array (e.g. `GET
    /users/sso-providers`'s `oneOf: [array-of-typed-object,
    array-of-empty-object]`, from a handler with more than one `res.json`
    call site) — return the items schema to type the array's elements
    with. Returns `{}` (meaning "no further typing", i.e. `List[Any]`)
    when the variants disagree on item shape rather than arbitrarily
    picking one, and `None` when `schema` isn't array-shaped at all.

    `_return_type_and_constructor` and `GeneratedOp.emit_contract_test`
    both call this — they used to each hardcode their own `schema.get
    ("type") == "array"` check, which only handled the *direct* case and
    silently diverged into two different wrong answers for the oneOf-of-
    arrays case (a real op — see the test-generation commit this was
    fixed in — that's why this is a shared helper now, not two copies).
    """
    if not schema:
        return None
    if schema.get("type") == "array":
        return schema.get("items") or {}
    for key in ("oneOf", "anyOf"):
        variants = schema.get(key)
        if variants and all(isinstance(v, dict) and v.get("type") == "array" for v in variants):
            items_list = [v.get("items") or {} for v in variants]
            first = items_list[0]
            return first if all(i == first for i in items_list) else {}
    return None


# --------------------------------------------------------------------------
# JSON Schema -> synthetic example value (for tests/contract/, not runtime)
# --------------------------------------------------------------------------


def example_for_schema(schema: dict[str, Any] | None) -> Any:
    """A minimal, deterministic JSON-shaped value matching `schema`, used
    to fill request bodies/query params and canned mock responses in the
    generated contract tests (docs/sdk-plan.md's testing-decision note).
    These are placeholders picked for shape, not realism — a contract
    test cares that the right field names round-trip, not that
    `password` looks like a real password.
    """
    if not schema:
        return "x"
    if schema.get("x-confidence") == "unknown":
        return "x"
    if "const" in schema:
        return schema["const"]
    if "enum" in schema:
        return schema["enum"][0]
    if "oneOf" in schema:
        return example_for_schema(schema["oneOf"][0])
    if "anyOf" in schema:
        return example_for_schema(schema["anyOf"][0])

    t = schema.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        return example_for_schema({**schema, "type": non_null[0]}) if non_null else None

    if t == "object":
        return {k: example_for_schema(v) for k, v in (schema.get("properties") or {}).items()}
    if t == "array":
        items = schema.get("items")
        return [example_for_schema(items)] if items else []
    if t == "string":
        return "x"
    if t == "integer":
        return 1
    if t == "number":
        return 1.0
    if t == "boolean":
        return True
    return "x"


