# --------------------------------------------------------------------------
# naming
# --------------------------------------------------------------------------


def snake_case(segment: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", segment)
    s = re.sub(r"(?<!^)(?=[A-Z])", "_", s)
    s = re.sub(r"_+", "_", s)
    return s.lower().strip("_")


def default_method_name(method: str, path: str) -> str:
    """The naming rule from docs/sdk-plan.md section 8, for the ops the
    resource-map doesn't override.
    """
    method = method.upper()
    segments = [s for s in path.split("/") if s]
    last = segments[-1] if segments else ""
    last_is_param = last.startswith("{") and last.endswith("}")

    if last_is_param:
        if method == "GET":
            return "retrieve"
        if method in ("PUT", "PATCH"):
            return "update"
        if method == "DELETE":
            return "delete"
        segments = segments[:-1]
        last = segments[-1] if segments else ""

    if method == "POST" and not last_is_param and len(segments) == 1:
        return "create"

    return snake_case(last) or "call"


def path_param_names(path: str) -> list[str]:
    return re.findall(r"\{([^}]+)\}", path)


def python_param_name(openapi_param_name: str) -> str:
    return snake_case(openapi_param_name) or openapi_param_name.lower()


