class Operation:
    def __init__(self, method: str, path: str, op: dict[str, Any]) -> None:
        self.method = method.upper()
        self.path = path
        self.op = op
        self.operation_id: str = op["operationId"]
        self.summary: str = op.get("summary", "")
        self.description: str = op.get("description", "")
        self.service: str = (op.get("servers") or [{}])[0].get("description", "database")
        self.source = op.get("x-source", {})

    @property
    def path_params(self) -> list[dict[str, Any]]:
        return [p for p in self.op.get("parameters", []) if p.get("in") == "path"]

    @property
    def query_params(self) -> list[dict[str, Any]]:
        return [p for p in self.op.get("parameters", []) if p.get("in") == "query"]

    @property
    def body_schema(self) -> dict[str, Any] | None:
        rb = self.op.get("requestBody")
        if not rb:
            return None
        content = rb.get("content", {})
        json_body = content.get("application/json")
        if json_body is None:
            raise NotImplementedError(
                f"{self.method} {self.path}: non-JSON request body "
                f"(content types: {list(content)}) — multipart is out of "
                f"scope for the F3 pilot (see generate.py's module docstring)."
            )
        return json_body.get("schema")

    @property
    def response_schema(self) -> dict[str, Any] | None:
        responses = self.op.get("responses", {})
        for code in ("200", "201"):
            r = responses.get(code)
            if r and "content" in r:
                content = r["content"].get("application/json")
                if content:
                    return content.get("schema")
        return None

    @property
    def is_204(self) -> bool:
        responses = self.op.get("responses", {})
        return "204" in responses and not any(c in responses for c in ("200", "201"))


def load_spec() -> dict[str, Any]:
    return json.loads(SPEC_PATH.read_text(encoding="utf-8"))


def index_operations(spec: dict[str, Any]) -> dict[str, Operation]:
    by_id: dict[str, Operation] = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            operation = Operation(method, path, op)
            by_id[operation.operation_id] = operation
    return by_id


