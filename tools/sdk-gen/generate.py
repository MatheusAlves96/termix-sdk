#!/usr/bin/env python3
"""tools/sdk-gen: OpenAPI + resource-map.json -> src/termix_sdk/{resources,models,types}/*.py

F3 pilot (docs/sdk-plan.md phase F3). Deliberately scoped to the two
modules resource-map.json currently lists (`system`, `credentials`) —
both pure-JSON, no multipart — to prove the generation pattern end to
end before F4 runs it across all 491 operations. Known simplifications,
to be lifted in F4:

  - A nested `object`/`array` field inside a response or request body
    becomes `dict[str, Any]`/`list[Any]` rather than its own generated
    class — only top-level fields get a real type.
  - `oneOf`/`anyOf` at the top level of a response makes the method
    return the base `TermixObject` rather than a `Union` of variants.
  - Every request-body field is treated as optional in the generated
    TypedDict (`total=False`), regardless of the spec's own `required`
    list, to sidestep TypedDict's required/optional split for now.
  - No `x-requires-admin`/`x-requires-data-access` docstring callouts yet.
  - multipart/form-data bodies are out of scope entirely (none of the
    piloted ops have one) — `hosts` needs that and is deferred to F4.

Usage: python tools/sdk-gen/generate.py [--check] from the repo root.
--check re-generates into a temp dir and diffs against what's committed,
without writing, for CI use once this is wired into F4.
"""

