class GeneratedOp:
    """Everything generate_module() needs to emit one method + its
    TypedDict + its contribution to the module's response model(s).
    """

    def __init__(
        self, op: Operation, method_name: str, class_prefix: str, module_name: str
    ) -> None:
        self.op = op
        self.method_name = method_name
        self.class_prefix = class_prefix  # PascalCase resource name, e.g. "Credentials"
        self.module_name = module_name  # client attribute name, e.g. "credentials"

    @property
    def params_class_name(self) -> str:
        return f"{self.class_prefix}{_pascal(self.method_name)}Params"

    def has_params(self) -> bool:
        return bool(self.op.body_schema) or bool(self.op.query_params)

    def python_path_args(self) -> list[str]:
        return [python_param_name(p["name"]) for p in self.op.path_params]

    def emit_params_typeddict(self) -> str | None:
        if not self.has_params():
            return None
        fields: dict[str, str] = {}
        for p in self.op.query_params:
            fields[p["name"]] = schema_to_type(p.get("schema"))
        body_schema = self.op.body_schema
        if body_schema and body_schema.get("type") == "object":
            for name, prop_schema in (body_schema.get("properties") or {}).items():
                fields[name] = schema_to_type(prop_schema)
        if not fields:
            return None
        lines = [f"class {self.params_class_name}(TypedDict, total=False):"]
        for name, type_str in fields.items():
            lines.append(f"    {name}: {type_str}")
        return "\n".join(lines)

    def emit_method(self, *, is_async: bool) -> str:
        op = self.op
        query_names = {p["name"] for p in op.query_params}
        body_schema = op.body_schema
        body_names = set((body_schema or {}).get("properties", {})) if body_schema else set()

        path_args = self.python_path_args()
        # **params (if any) must be the last parameter — options is a
        # named keyword-only arg with a default, so it has to come before
        # it, not after.
        sig_parts = ["self"] + [f"{a}: str" for a in path_args]
        sig_parts.append("*")
        sig_parts.append("options: RequestOptions | None = None")
        if self.has_params():
            sig_parts.append(f"**params: Unpack[{self.params_class_name}]")
        signature = ", ".join(sig_parts)

        return_type, construct_expr = self._return_type_and_constructor("response")

        awaited = "await " if is_async else ""
        async_kw = "async " if is_async else ""

        raw_names = [p["name"] for p in op.path_params]
        path_expr = op.path
        for raw, py_name in zip(raw_names, path_args):
            path_expr = path_expr.replace("{" + raw + "}", "{" + py_name + "}")
        path_literal = f'f"{path_expr}"' if path_args else f'"{path_expr}"'

        one_line_def = f"    {async_kw}def {self.method_name}({signature}) -> {return_type}:"
        # Measure against the *worst case* width, not today's: ruff's own
        # later UP035 pass may still rewrite `List[X]`/`Dict[X]` here into
        # `builtins.list[X]`/`builtins.dict[X]` (+9/+9 chars) to dodge a
        # same-named `list`/`dict` method — see the `builtins.list`
        # disambiguation this project relies on (F3 pilot commit). If we
        # measure only the pre-substitution string, a line that fits *now*
        # can silently overflow once ruff grows the return type later,
        # since ruff format's own heuristic won't retroactively re-wrap a
        # short parameter list just because a lint fix made it longer.
        worst_case_len = len(
            one_line_def.replace("List[", "builtins.list[").replace("Dict[", "builtins.dict[")
        )
        if worst_case_len <= 95:
            lines = [one_line_def]
        else:
            # ruff format's own line-splitting heuristic won't break a
            # short parameter list just because the *return type* is what
            # makes the line too long (e.g. `builtins.list[FooItem]` after
            # the `list`-method-name disambiguation) — so long
            # signatures are pre-wrapped here rather than left for it.
            # A trailing comma is Black/ruff format's "magic trailing
            # comma": it's what actually keeps this exploded across
            # `ruff format` runs — without it ruff collapses a short
            # parameter list back onto one line regardless of the
            # resulting width, undoing the wrap on every regeneration.
            lines = [
                f"    {async_kw}def {self.method_name}(",
                f"        {signature},",
                f"    ) -> {return_type}:",
            ]
        doc = op.summary or op.description
        if doc:
            src = op.source
            lines.append(f'        """{doc}')
            lines.append("")
            lines.append(f"        {op.method} {op.path}")
            if src.get("file"):
                lines.append(f"        Source: {src['file']}:{src['line']}")
            lines.append('        """')

        if query_names and body_names:
            lines.append(
                f"        query = {{k: params[k] for k in {sorted(query_names)!r} if k in params}}"
            )
            lines.append("        body = {k: v for k, v in params.items() if k not in query}")
            call_kwargs = "query=query or None, json_body=body or None"
        elif query_names:
            call_kwargs = "query=dict(params) or None" if self.has_params() else "query=None"
        elif body_names or (body_schema is not None):
            call_kwargs = (
                "json_body=dict(params) or None" if self.has_params() else "json_body=None"
            )
        else:
            call_kwargs = ""

        request_call = (
            f'{awaited}self._request("{op.method}", {path_literal}'
            + (f", {call_kwargs}" if call_kwargs else "")
            + ", options=options)"
        )
        lines.append(f"        response = {request_call}")
        lines.append(f"        return {construct_expr}")
        lines.append("")
        return "\n".join(lines)

    def _return_type_and_constructor(self, response_var: str) -> tuple[str, str]:
        op = self.op
        if op.is_204:
            return "None", "None"

        schema = op.response_schema
        if schema is None:
            return "TermixObject | None", (
                f"TermixObject.construct_from({response_var}.data if {response_var} else None, "
                f"last_response={response_var})"
            )

        model_name = self._model_name_for(schema)
        items_schema = resolve_array_items(schema)
        if items_schema is not None:
            if items_schema.get("type") == "object" and items_schema.get("properties"):
                inner = f"{self.class_prefix}{_pascal(self.method_name)}Item"
                return f"List[{inner}]", (
                    f"{inner}.construct_from({response_var}.data if {response_var} else [], "
                    f"last_response={response_var})"
                )
            return "List[Any]", (f"({response_var}.data if {response_var} else [])")

        if model_name:
            return model_name, (
                f"{model_name}.construct_from({response_var}.data if {response_var} else None, "
                f"last_response={response_var})"
            )

        object_type = "TermixObject | None" if schema_allows_null(schema) else "TermixObject"
        return object_type, (
            f"TermixObject.construct_from({response_var}.data if {response_var} else None, "
            f"last_response={response_var})"
        )

    def _model_name_for(self, schema: dict[str, Any]) -> str | None:
        if "oneOf" in schema or "anyOf" in schema:
            return None
        if schema.get("type") not in (None, "object"):
            return None
        return f"{self.class_prefix}{_pascal(self.method_name)}Result"

    def emit_model_class(self) -> str | None:
        """A model for this op's own response, only when it's worth a
        dedicated class (a plain object with properties). Named after the
        operation rather than shared across ops in the pilot — a real
        per-resource `Credential`/`Host` model (reused across list/create/
        retrieve/update) is F4 work, once response schemas are less
        frequently the per-op inline shape they are today (see
        docs/spec-generation-strategy.md's response-typing numbers).
        """
        schema = self.op.response_schema
        if schema is None:
            return None
        items_schema = resolve_array_items(schema)
        if items_schema is not None:
            if items_schema.get("type") == "object" and items_schema.get("properties"):
                name = f"{self.class_prefix}{_pascal(self.method_name)}Item"
                return self._emit_class(name, items_schema)
            return None
        model_name = self._model_name_for(schema)
        if model_name is None:
            return None
        return self._emit_class(model_name, schema)

    def _emit_class(self, name: str, schema: dict[str, Any]) -> str:
        properties = schema.get("properties") or {}
        lines = [f"class {name}(TermixObject):"]
        if not properties:
            lines.append(f'    """{self.op.method} {self.op.path}.')
            if schema.get("x-note"):
                lines.append("")
                lines.append("    Opaque: the spec has no field-level schema for this response.")
            lines.append('    """')
            lines.append("    pass")
        else:
            for prop_name, prop_schema in properties.items():
                lines.append(f"    {prop_name}: {schema_to_type(prop_schema)}")
        return "\n".join(lines)

    # -- contract-test support (docs/sdk-plan.md testing-decision note) ---

    def example_path_values(self) -> dict[str, Any]:
        return {
            python_param_name(p["name"]): example_for_schema(p.get("schema"))
            for p in self.op.path_params
        }

    def example_query_kwargs(self) -> dict[str, Any]:
        return {p["name"]: example_for_schema(p.get("schema")) for p in self.op.query_params}

    def example_body_kwargs(self) -> dict[str, Any]:
        body_schema = self.op.body_schema
        if not body_schema or body_schema.get("type") != "object":
            return {}
        return {
            name: example_for_schema(prop_schema)
            for name, prop_schema in (body_schema.get("properties") or {}).items()
        }

    def example_response_body(self) -> Any:
        if self.op.is_204:
            return None
        schema = self.op.response_schema
        if schema is None:
            # No documented schema at all: a non-empty placeholder so the
            # method still gets a real object back to assert isinstance
            # on, instead of the `None` an empty mock body would produce.
            return {"x-contract-test-placeholder": True}
        return example_for_schema(schema)

    def emit_contract_test(self, *, is_async: bool) -> str:
        """One pytest test per operation: feeds the method a synthetic
        example of every param the spec documents, queues a synthetic
        example of the documented response, and asserts the SDK sent the
        right method/path/query/body and parsed the response into the
        right shape. Data is synthetic (docs/sdk-plan.md's
        testing-decision note) — this is a contract test against the
        spec, not a live call against a real Termix instance.
        """
        op = self.op
        path_values = self.example_path_values()
        query_kwargs = self.example_query_kwargs()
        body_kwargs = self.example_body_kwargs()
        response_body = self.example_response_body()

        prefix = "async_" if is_async else ""
        await_ = "await " if is_async else ""
        async_def = "async def" if is_async else "def"
        fixture = "async_client" if is_async else "client"
        mock_fixture = "mock_async_http_client" if is_async else "mock_http_client"

        call_args = [repr(path_values[a]) for a in self.python_path_args()]
        call_kwargs = {**query_kwargs, **body_kwargs}
        call_args_str = ", ".join([*call_args, *(f"{k}={v!r}" for k, v in call_kwargs.items())])

        path_literal = op.path
        for raw, py_name in zip(
            [p["name"] for p in op.path_params], self.python_path_args(), strict=True
        ):
            path_literal = path_literal.replace("{" + raw + "}", str(path_values[py_name]))

        lines: list[str] = []
        if is_async:
            lines.append("@pytest.mark.asyncio")
        lines.append(
            f"{async_def} test_{prefix}{self.method_name}_contract({fixture}, {mock_fixture}):"
        )
        lines.append(f'    """Generated from {op.method} {op.path} in spec/termix-openapi.json."""')
        lines.append(f"    {mock_fixture}.queue_response(status_code=200, body={response_body!r})")
        lines.append(
            f"    result = {await_}{fixture}.{self.module_name}.{self.method_name}({call_args_str})"
        )
        lines.append(f"    sent = {mock_fixture}.requests[0]")
        lines.append(f'    assert sent.method == "{op.method}"')
        lines.append(f'    assert sent.url.endswith("{path_literal}")')
        if query_kwargs:
            lines.append(f"    assert sent.params == {query_kwargs!r}")
        if body_kwargs:
            lines.append(f"    assert sent.json == {body_kwargs!r}")
        if op.is_204:
            lines.append("    assert result is None")
        else:
            items_schema = resolve_array_items(op.response_schema)
            items_have_dedicated_model = bool(
                items_schema
                and items_schema.get("type") == "object"
                and items_schema.get("properties")
            )
            if isinstance(response_body, list) and items_have_dedicated_model:
                # result is a list of a generated model, not raw dicts — a
                # nested object/array field on that model is itself a
                # TermixObject at runtime regardless of its static type
                # annotation (see _object.py's construct_from), so compare
                # via to_dict() rather than the model instances directly.
                lines.append(f"    assert len(result) == {len(response_body)}")
                if response_body:
                    lines.append(f"    assert result[0].to_dict() == {response_body[0]!r}")
            elif isinstance(response_body, list):
                # A bare List[Any] response is never wrapped — result is
                # the raw list exactly as the mock returned it.
                lines.append(f"    assert result == {response_body!r}")
            elif isinstance(response_body, dict) and response_body:
                lines.append(f"    assert result.to_dict() == {response_body!r}")
            else:
                # A scalar response, or a dict with no fields at all —
                # still confirm the method didn't swallow a non-empty
                # response into `None`.
                lines.append("    assert result is not None")
        return "\n".join(lines) + "\n"


def _pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_") if part)


